/**
 * Helper to get or dynamically generate rich storytelling content for any brand
 */
export function getBrandContent(brand) {
  if (!brand) return null;
  const slug = (brand.slug || '').toLowerCase().trim();
  const name = brand.name || slug.replace(/-/g, ' ').replace(/\b\w/g, l => l.toUpperCase());

  // Check curated stories
  if (BRAND_STORIES[slug]) {
    return {
      ...BRAND_STORIES[slug],
      name: name,
      slug: slug,
    };
  }

  // Intelligent fallback for all other brands
  return {
    origin_country: brand.origin_country || "International Luxury",
    founded_year: brand.founded_year || "Prestige House",
    fragrance_style: brand.fragrance_style || "Niche Haute Parfumerie & Signature Flacons",
    tagline: `Authentic Luxury Fragrances by ${name} Available in Dubai, UAE`,
    description: brand.description || `${name} is an esteemed fragrance house celebrated for its commitment to exceptional olfactory craftsmanship, exquisite raw essences, and distinctive signature flacons. Curated directly for fragrance enthusiasts at our Gold Souk Dubai boutique, each ${name} creation delivers an unforgettable sensory trail of distinction and luxury.`,
    history: `${name} has earned admiration among discerning perfume connoisseurs for its harmonious balance of classical perfumery traditions and contemporary elegance. 100% authentic original UAE stock guaranteed.`,
    specialties: "Precious Botanicals, Rare Woods, Refined Florals, and Long-Lasting Artisanal Sillage."
  };
}
